async (page) => {
    const base = new URL(page.url()).origin;
    const errors = [];
    const failedResources = [];
    page.on('pageerror', error => errors.push(error.message));
    page.on('response', response => { if (response.status() >= 400 && response.request().method() === 'GET') failedResources.push(response.status()); });
    await page.addInitScript(() => {
        Object.defineProperty(navigator, 'clipboard', {configurable: true, value: {writeText: async value => { window.qaCopiedPassword = value; }}});
    });
    await page.goto(base + '/admin/password');
    const generated = page.locator('#new-password');
    const confirmation = page.locator('#confirm-password');
    const copy = page.locator('[data-password-copy]');
    const length = page.locator('[data-password-length]');
    const generate = page.getByRole('button', {name: 'Сгенерировать пароль', exact: true});
    if (await length.inputValue() !== '20' || await page.locator('[data-password-exclude-similar]').count()) throw new Error('Generator defaults');
    if (!await copy.isDisabled()) throw new Error('Copy should be disabled before typing');
    let posts = 0;
    page.on('request', request => { if (request.method() === 'POST' && request.url().includes('/admin/password')) posts++; });
    await page.getByRole('button', {name: 'Сгенерировать пароль', exact: true}).click();
    const password = await generated.inputValue();
    if (!/^[A-Za-z0-9_-]{20}$/.test(password) || /[0Oo1Il]/.test(password) || await confirmation.inputValue() !== password) throw new Error('Generated password/confirmation');
    if (await generated.getAttribute('type') !== 'password') throw new Error('Generated password should start hidden');
    await copy.click();
    if (!await page.evaluate(value => window.qaCopiedPassword === value, password)) throw new Error('Copy mismatch');
    if (!await page.locator('[data-password-feedback]').getByText('Пароль скопирован.', {exact: true}).count()) throw new Error('Copy feedback');
    await page.evaluate(() => { navigator.clipboard.writeText = async () => { throw new DOMException('QA clipboard denied', 'NotAllowedError'); }; });
    await copy.click();
    if (!(await page.locator('[data-password-feedback]').innerText()).includes('вручную') || await generated.inputValue() !== password) throw new Error('Clipboard failure fallback');
    const toggle = generated.locator('..').getByRole('button');
    await toggle.click();
    if (await generated.getAttribute('type') !== 'text' || await toggle.getAttribute('aria-pressed') !== 'true') throw new Error('Show password');
    await toggle.focus();
    await page.keyboard.press('Space');
    if (await generated.getAttribute('type') !== 'password') throw new Error('Keyboard hide password');
    await toggle.click();
    const confirmationToggle = confirmation.locator('..').getByRole('button');
    await confirmationToggle.click();
    await generate.click();
    if (await generated.getAttribute('type') !== 'password' || await confirmation.getAttribute('type') !== 'password' || await toggle.getAttribute('aria-pressed') !== 'false' || await confirmationToggle.getAttribute('aria-pressed') !== 'false') throw new Error('Regeneration should hide both fields');
    const previous = await generated.inputValue();
    await length.fill('16');
    if (await generated.inputValue() !== previous) throw new Error('Settings changed existing password');
    await generate.click();
    if ((await generated.inputValue()).length !== 16) throw new Error('Minimum length');
    await length.fill('64');
    await generate.click();
    if ((await generated.inputValue()).length !== 64 || await confirmation.inputValue() !== await generated.inputValue()) throw new Error('Maximum length');
    for (const invalid of ['15', '65', '20.5', '']) {
        const before = await generated.inputValue();
        await length.fill(invalid);
        await generate.click();
        if (await generated.inputValue() !== before || await length.getAttribute('aria-invalid') !== 'true') throw new Error('Invalid length changed password');
    }
    await page.getByLabel('Текущий пароль', {exact: true}).fill('manual-check-only');
    await generated.fill('manual-check-only');
    await confirmation.fill('manual-check-only');
    if (!await generated.evaluate(input => input.form.checkValidity())) throw new Error('Generator settings blocked manual password form');
    await page.getByLabel('Текущий пароль', {exact: true}).fill('');
    await length.fill('16');
    await page.evaluate(() => {
        window.qaOriginalRandom = crypto.getRandomValues.bind(crypto);
        crypto.getRandomValues = array => {
            const bytes = [232, 255, 0, 231, 58, 1];
            array.forEach((_, index) => { array[index] = bytes[index % bytes.length]; });
            return array;
        };
    });
    await generate.click();
    const pool = [...'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-_'].filter(char => !'0Oo1Il'.includes(char));
    const expected = [pool[0], pool[57], pool[0], pool[1]].join('').repeat(4);
    if (await generated.inputValue() !== expected) throw new Error('Rejection sampling boundaries');
    await page.evaluate(() => { crypto.getRandomValues = array => { array.fill(0); return array; }; });
    await generate.click();
    if (await generated.inputValue() !== 'A'.repeat(16)) throw new Error('Filtered alphabet mapping');
    await page.evaluate(() => { crypto.getRandomValues = array => { array.fill(255); return array; }; });
    await generate.click();
    if (await generated.inputValue() !== 'A'.repeat(16) || !(await page.locator('[data-password-feedback]').innerText()).includes('Не удалось')) throw new Error('Unusable random source should terminate without losing input');
    await page.evaluate(() => { crypto.getRandomValues = () => { throw new Error('QA API failure'); }; });
    await generate.click();
    if (await generated.inputValue() !== 'A'.repeat(16)) throw new Error('Crypto failure destroyed previous input');
    await page.evaluate(() => { crypto.getRandomValues = window.qaOriginalRandom; });
    await length.fill('20');
    await length.press('Enter');
    if ((await generated.inputValue()).length !== 20) throw new Error('Keyboard generation');
    await page.getByText('Дополнительные настройки', {exact: true}).click();
    const groups = page.locator('[data-password-group]');
    const symbols = page.locator('[data-password-custom-symbols]');
    const excluded = page.locator('[data-password-excluded-chars]');
    const strict = page.locator('[data-password-require-groups]');
    for (const group of await groups.all()) await group.uncheck();
    const existing = await generated.inputValue();
    await generate.click();
    if (await generated.inputValue() !== existing || !(await page.locator('[data-password-feedback]').innerText()).includes('Выберите')) throw new Error('No groups validation');
    await page.locator('[data-password-group=digits]').check();
    await generate.click();
    if (!/^[2-9]{20}$/.test(await generated.inputValue()) || !(await page.locator('[data-password-feedback]').innerText()).includes('увеличить')) throw new Error('Digits-only or weak settings warning');
    await page.locator('[data-password-group=digits]').uncheck();
    await page.locator('[data-password-group=symbols]').check();
    await symbols.fill('!!__--');
    await page.evaluate(() => { crypto.getRandomValues = array => { array.forEach((_, i) => { array[i] = i % 3; }); return array; }; });
    await generate.click();
    if (await generated.inputValue() !== '!_-'.repeat(7).slice(0, 20)) throw new Error('Duplicate symbols changed weights');
    await excluded.fill('_');
    await generate.click();
    if (!/^[!-]{20}$/.test(await generated.inputValue())) throw new Error('Custom exclusion');
    for (const invalid of ['!', '', 'abc', ' ', '«»']) {
        const old = await generated.inputValue();
        await symbols.fill(invalid);
        await generate.click();
        if (await generated.inputValue() !== old) throw new Error('Invalid or singleton symbols changed password');
    }
    await symbols.fill('!_-');
    await excluded.fill('!_-');
    const beforeEmpty = await generated.inputValue();
    await generate.click();
    if (await generated.inputValue() !== beforeEmpty) throw new Error('Empty filtered alphabet changed password');
    await excluded.fill('');
    await symbols.fill('-_');
    for (const group of await groups.all()) await group.check();
    await strict.check();
    await page.evaluate(() => { crypto.getRandomValues = window.qaOriginalRandom; });
    await generate.click();
    const balanced = await generated.inputValue();
    if (!/[a-z]/.test(balanced) || !/[A-Z]/.test(balanced) || !/[2-9]/.test(balanced) || !/[-_]/.test(balanced)) throw new Error('Required groups missing');
    await page.evaluate(() => { window.qaAttempts = 0; crypto.getRandomValues = array => { window.qaAttempts++; array.fill(0); return array; }; });
    await generate.click();
    if (await generated.inputValue() !== balanced || await page.evaluate(() => window.qaAttempts) !== 256) throw new Error('Strict generation attempt limit');
    await page.evaluate(() => { crypto.getRandomValues = window.qaOriginalRandom; });
    await strict.uncheck();
    await generated.fill('');
    if (!await copy.isDisabled()) throw new Error('Copy stale password');
    if (posts !== 0) throw new Error('Generate/show/copy submitted the form');
    await confirmation.fill('');
    for (const width of [1440, 768, 320]) {
        await page.setViewportSize({width, height: 1000});
        if (await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)) throw new Error('Password form overflow at ' + width);
        const editor = page.getByRole('navigation', {name: 'Разделы управления'}).getByRole('link', {name: 'Визуальный редактор', exact: true});
        const divider = await editor.locator('..').evaluate(item => ({top: getComputedStyle(item).borderTopWidth, start: getComputedStyle(item).borderInlineStartWidth}));
        if (parseFloat(width < 960 ? divider.start : divider.top) < 1) throw new Error('Password/editor divider missing at ' + width);
        if (await editor.getAttribute('href') !== '/') throw new Error('Visual editor destination changed');
    }
    await page.setViewportSize({width: 1440, height: 1000});
    await page.goto(base + '/admin/password');
    await page.screenshot({path: 'var/password-generator.png', fullPage: true});
    const anonymous = await page.context().browser().newContext();
    const login = await anonymous.newPage();
    await login.goto(base + '/admin/login');
    const loginPassword = login.locator('#password');
    await loginPassword.fill('Example-for-display-only');
    await login.getByRole('button', {name: 'Показать пароль', exact: true}).click();
    if (await loginPassword.getAttribute('type') !== 'text') throw new Error('Login show password');
    await login.getByRole('button', {name: 'Скрыть пароль', exact: true}).click();
    if (await loginPassword.getAttribute('type') !== 'password') throw new Error('Login hide password');
    if (await login.locator('[data-password-generate]').count()) throw new Error('Generator should not suggest a new password for sign-in');
    await loginPassword.fill('');
    await login.setViewportSize({width: 320, height: 900});
    if (await login.evaluate(() => document.documentElement.scrollWidth > innerWidth)) throw new Error('Login overflow');
    await anonymous.close();
    const unavailable = await page.context().browser().newContext({storageState: await page.context().storageState()});
    await unavailable.addInitScript(() => { Object.defineProperty(crypto, 'getRandomValues', {value: undefined}); });
    const unsupported = await unavailable.newPage();
    await unsupported.goto(base + '/admin/password');
    if (!await unsupported.locator('[data-password-generate]').isDisabled() || !(await unsupported.locator('[data-password-feedback]').innerText()).includes('недоступна')) throw new Error('Missing crypto fallback');
    await unsupported.locator('#new-password').fill('manual-entry-only');
    if (await unsupported.locator('[data-password-copy]').isDisabled()) throw new Error('Manual copy without crypto');
    await unavailable.close();
    const noJs = await page.context().browser().newContext({javaScriptEnabled: false, storageState: await page.context().storageState()});
    const plain = await noJs.newPage();
    await plain.goto(base + '/admin/password');
    if (await plain.locator('input[type=password]').count() !== 3 || !await plain.locator('[data-password-generator]').isHidden() || !await plain.locator('[data-password-strength]').isHidden()) throw new Error('No-JS fallback');
    if (await plain.getByRole('button', {name: 'Показать пароль', exact: true}).count()) throw new Error('Inactive no-JS controls visible');
    await noJs.close();
    if (errors.length) throw new Error(errors.join('\n'));
    if (failedResources.length) throw new Error('Failed resources: ' + failedResources.join(','));
    return 'PASS: uniform generation/rejection boundaries, lengths/groups/custom exclusions/deduplication/strict limits, crypto failures, manual form independence, copy, hidden regeneration, keyboard/no-JS and responsive divider';
}
