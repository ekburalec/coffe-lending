async (page) => {
    const base = new URL(page.url()).origin;
    await page.setViewportSize({width: 1440, height: 1000});
    await page.emulateMedia({reducedMotion: 'reduce'});
    await page.goto(base + '/admin/visual-editor');
    const preview = page;
    const heading = preview.locator('[data-visual-text="copy-1"]');
    await page.waitForFunction(() => document.querySelector('[data-visual-text="copy-1"]').isContentEditable);
    await heading.focus();
    await heading.press('Tab');
    const next = preview.locator('[data-visual-text="copy-2"]');
    if (!await next.evaluate(element => element === document.activeElement && element.matches(':focus-visible') && getComputedStyle(element).outlineStyle !== 'none')) throw new Error('Keyboard focus not visible');
    const picture = preview.locator('[data-visual-image="image-0"]');
    await picture.focus();
    await picture.press('Enter');
    if (!await page.locator('[data-visual-photo]').isVisible()) throw new Error('Keyboard photo activation failed');
    await page.locator('[data-visual-photo-file]').setInputFiles({name: 'bad.svg', mimeType: 'image/svg+xml', buffer: Buffer.from('<svg/>')});
    if (!(await page.locator('[data-visual-photo-error]').innerText()).includes('JPG')) throw new Error('Photo error not in dialog');
    await page.setViewportSize({width: 320, height: 900});
    const box = await page.locator('[data-visual-photo]').boundingBox();
    if (box.x < 0 || box.x + box.width > 320) throw new Error('Photo dialog overflows phone');
    await page.keyboard.press('Escape');
    if (!await picture.evaluate(element => element === document.activeElement)) throw new Error('Photo focus not returned');
    await page.setViewportSize({width: 1440, height: 1000});
    await heading.fill('Не выходить без решения');
    await page.getByRole('button', {name: 'Выйти', exact: true}).click();
    if (!await page.locator('[data-visual-leave]').isVisible()) throw new Error('Logout did not guard draft');
    await page.getByRole('button', {name: 'Остаться', exact: true}).click();
    if (await heading.innerText() !== 'Не выходить без решения') throw new Error('Logout guard lost draft');
    await page.locator('[data-visual-cancel]').click();
    await page.locator('[data-visual-mode-toggle]').click();
    if (await heading.getAttribute('role') !== null || await heading.evaluate(element => element.isContentEditable)) throw new Error('Preview did not restore heading semantics');
    const noJs = await page.context().browser().newContext({javaScriptEnabled: false});
    const plain = await noJs.newPage();
    await plain.goto(base + '/');
    if (await plain.locator('[data-product]').count() !== 9 || await plain.locator('[data-occasion-panel]:visible').count() !== 3) throw new Error('Public no-JS content regressed');
    if (await plain.locator('[data-visual-text],[data-visual-image]').count()) throw new Error('Editor metadata leaked to public');
    await noJs.close();
    return 'PASS: keyboard editing/photo activation, focus restoration, visible file errors, mobile dialog, logout guard, preview semantics, public no-JS';
}
